def build(old):
    assert len(old)==20
    selected=list(old);new={}
    for ci,cat in enumerate(CATS):
        assert len(ADDITIONS[cat])==15
        rows=[dict(id=f'cal80_{cat}_{i:02d}',category=cat,template=f'expanded_{cat}_{i:02d}',prompt=x,
                   expected_answer=y,evaluator='manual_reference_only') for i,(x,y) in enumerate(ADDITIONS[cat])]
        random.Random(926010000+ci).shuffle(rows);new[cat]=rows
    for a,b in [(0,5),(5,15)]:
        for cat in CATS:selected.extend(new[cat][a:b])
    assert len(selected)==80 and len({r['prompt'] for r in selected})==80
    for n in [20,40,80]:
        assert all(sum(r['category']==cat for r in selected[:n])==n//4 for cat in CATS)
    return selected
